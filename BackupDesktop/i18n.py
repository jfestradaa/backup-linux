def _is_spanish():
    candidates = [os.environ.get(key, "") for key in ("LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG")]
    for candidate in candidates:
        if candidate:
            return candidate.split(":", 1)[0].lower().startswith("es")
    return False


